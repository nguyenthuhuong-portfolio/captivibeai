export const dictionaries: Record<Language, Record<TranslationKey, string>> = { en, vi }

export type TranslateParams = Record<string, string | number>

export function translate(language: Language, key: TranslationKey, params?: TranslateParams) {
  const template = dictionaries[language][key] ?? dictionaries.en[key]
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, token: string) =>
    token in params ? String(params[token]) : match,
  )
}
